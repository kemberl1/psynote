/** Очевидные опечатки модели в клинических формулировках. */

const OBVIOUS_TYPOS: ReadonlyArray<readonly [string, string]> = [
  ["Сидрос", "Синдром"],
  ["сидрос", "синдром"],
  ["СИДРОС", "СИНДРОМ"],
  ["психмоторн", "психомоторн"],
  ["Психмоторн", "Психомоторн"],
  ["ПСИХМОТОРН", "ПСИХОМОТОРН"],
  ["самостоятельно не предъявляет", "не предъявляет"],
  ["Самостоятельно не предъявляет", "не предъявляет"],
  ["самостоятельно не формирует", "не предъявляет"],
  ["Самостоятельно не формирует", "не предъявляет"],
];

/** Заменяет только однозначные опечатки вроде «Сидрос» → «Синдром». */
export function fixObviousTypos(text: string): string {
  if (!text) return text;
  let out = text;
  for (const [from, to] of OBVIOUS_TYPOS) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  return out;
}
