// ЭТАП 3.2 — регресс-тесты precision-фикса отчеств. ВСЕ данные синтетические
// (вымышленные ФИО), реальные пациенты НЕ используются (docs/04 §7).
//
// Регрессия Этапа 3.1: гейт применял patronymicPattern ПОДСТРОКОЙ
// (FindAllStringIndex), поэтому ловил ПРЕФИКСЫ нарицательных слов с заглавной
// буквы («Налич» в «Наличие», «Различ» в «Различие») → fail-closed на ~100%
// дневников. Детектор же реагировал только на ЦЕЛЫЙ токен (isFullToken),
// поэтому требование гейта было невыполнимым → ложная блокировка.
//
// Фикс: гейт матчит отчество ПО ЦЕЛОМУ ТОКЕНУ той же логикой, что детектор
// (общий хелпер isWholePatronymic), и сам паттерн ужесточён (короткие «-ич» —
// закрытый список реальных отчеств вместо голого `[А-ЯЁ][а-яё]+ич`).

// TestTrapWordsKept — ГЛАВНЫЙ precision-тест. Слова-ловушки (нарицательные,
// совпадавшие с too-loose паттерном Этапа 3.1) НЕ должны вырезаться и НЕ должны
// ложно блокироваться гейтом — ни с заглавной (начало предложения), ни
// строчными.
func TestTrapWordsKept(t *testing.T) {
	p := newTestPipeline(t)

	cases := []struct {
		name string
		in   string
		keep string
	}{
		// Слова на «...личи...», ловившиеся префиксом `[А-ЯЁ][а-яё]+ич`.
		{"upper_nalichie", "Наличие галлюцинаций не выявлено.", "Наличие"},
		{"upper_kolichestvo", "Количество баллов в пределах нормы.", "Количество"},
		{"upper_razlichie", "Различие в поведении не отмечено.", "Различие"},
		{"upper_otlichie", "Отличие от прошлого осмотра минимально.", "Отличие"},
		{"phrase_bez_otlichij", "Состояние без отличий от вчерашнего.", "отличий"},
		// Те же корни строчными (середина предложения) — тоже целы.
		{"lower_nalichie", "Отмечено наличие тревоги по вечерам.", "наличие"},
		{"lower_kolichestvo", "Снижено количество приступов за неделю.", "количество"},
		{"lower_razlichie", "Существенное различие в анализах.", "различие"},
		// Нарицательные на «-ич», совпадавшие с голым `ич` как целый токен.
		{"upper_paralich", "Паралич конечностей не выявлен.", "Паралич"},
		{"lower_paralich", "Вялый паралич не подтверждён.", "паралич"},
		{"upper_moskvich", "Москвич по происхождению, адаптирован.", "Москвич"},
		{"lower_moskvich", "Коренной москвич, родился здесь.", "москвич"},
		{"upper_kulich", "Кулич принесли на праздник в отделение.", "Кулич"},
		{"lower_kulich", "Пациент ел кулич без принуждения.", "кулич"},
		// Слова с «ич»/«личн» в середине — не отчества.
		{"lichnost", "Личность сохранна, ориентирован верно.", "Личность"},
		{"konechnosti", "Конечности тёплые, отёков нет.", "Конечности"},
		{"privychnye", "Привычные действия выполняет самостоятельно.", "Привычные"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res := run(t, p, tc.in)
			if !strings.Contains(res.Text, tc.keep) {
				t.Errorf("нарицательное %q не должно вырезаться; got: %q", tc.keep, res.Text)
			}
			if strings.Contains(res.Text, "[ФИО") || strings.Contains(res.Text, "[ПАЦИЕНТ]") ||
				strings.Contains(res.Text, "[РОДИТЕЛЬ]") {
				t.Errorf("ловушка %q ложно заменена ФИО-плейсхолдером; got: %q", tc.keep, res.Text)
			}
			if !res.Clean {
				t.Errorf("чистый текст %q НЕ должен блокироваться гейтом (fail-closed regression); suspicions=%v",
					tc.in, res.Suspicions)
			}
		})
	}
}

// TestTrapWordsGateDirect — узкий тест на сам гейт: подаём слова-ловушки прямо в
// gate.inspect (как «уже анонимизированный» текст). Гейт НЕ должен находить
// остаточную ПДн — это прямое доказательство устранения асимметрии (подстрока →
// целый токен).
func TestTrapWordsGateDirect(t *testing.T) {
	p := newTestPipeline(t)

	clean := []string{
		"Наличие", "Количество", "Различие", "Отличие",
		"Наличие галлюцинаций не выявлено.",
		"Количество баллов снижено.",
		"Различие в поведении не отмечено.",
		"без отличий от вчерашнего осмотра",
		"Паралич", "паралич", "Москвич", "москвич", "Кулич", "кулич",
		"Личность", "Конечности", "Привычные",
	}
	for _, txt := range clean {
		t.Run(txt, func(t *testing.T) {
			if sus := p.gate.inspect(txt); len(sus) != 0 {
				t.Errorf("гейт ложно сработал на чистом тексте %q: %v", txt, sus)
			}
		})
	}
}

// TestShortPatronymicsRecall — recall коротких мужских отчеств на «-ич» во всех
// падежах. Закрытый список (Ильич/Кузьмич/Лукич/Фомич…) должен ловиться, тогда
// как нарицательные на «-ич» (проверено выше) — нет.
func TestShortPatronymicsRecall(t *testing.T) {
	p := newTestPipeline(t)

	cases := []struct {
		name   string
		in     string
		leaked string
	}{
		{"kuzmich_nom", "Осмотрен Кузьмич утром.", "Кузьмич"},
		{"kuzmich_gen", "Жалоба от Кузьмича принята.", "Кузьмича"},
		{"kuzmich_dat", "Передано Кузьмичу лично.", "Кузьмичу"},
		{"kuzmich_ins", "Беседа с Кузьмичом проведена.", "Кузьмичом"},
		{"kuzmich_pre", "Сведения о Кузьмиче занесены.", "Кузьмиче"},
		{"ilyich_nom", "Присутствовал Ильич на разборе.", "Ильич"},
		{"ilyich_ins", "Подписано Ильичом собственноручно.", "Ильичом"},
		{"lukich_gen", "Со слов Лукича выяснено следующее.", "Лукича"},
		{"fomich_dat", "Направлено Фомичу для сведения.", "Фомичу"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res := run(t, p, tc.in)
			if strings.Contains(res.Text, tc.leaked) {
				t.Errorf("короткое отчество %q просочилось; got: %q", tc.leaked, res.Text)
			}
			if !strings.Contains(res.Text, "[") {
				t.Errorf("ожидался ФИО-плейсхолдер для %q; got: %q", tc.in, res.Text)
			}
			if !res.Clean {
				t.Errorf("после вырезания отчества документ должен быть Clean=true; suspicions=%v", res.Suspicions)
			}
		})
	}
}

