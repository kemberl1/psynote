// TestMixedTrapAndRealPatronymic — интеграционный тест: синтетический «дневник»
// содержит И слова-ловушки (Наличие/Количество/Различие), И настоящее отчество
// в косвенном падеже, И короткое отчество. После Anonymize: отчества вырезаны,
// слова-ловушки целы, Clean=true (гейт не блокирует).
func TestMixedTrapAndRealPatronymic(t *testing.T) {
	p := newTestPipeline(t)

	doc := `Дневник наблюдения.
Наличие галлюцинаций не выявлено, количество приступов снижено.
Различие в поведении за неделю минимально, без отличий по соматике.
Беседа с Ивановичем проведена, со слов Петровны жалоб нет.
Осмотрен Кузьмич, состояние стабильное.`

	res, err := p.Anonymize(context.Background(), doc)
	if err != nil {
		t.Fatalf("Anonymize error: %v", err)
	}

	if !res.Clean {
		t.Fatalf("смешанный документ должен проходить гейт (Clean=true); suspicions=%v\ntext=%q",
			res.Suspicions, res.Text)
	}
	if err := Gate(res); err != nil {
		t.Errorf("Gate должен пропустить документ: %v", err)
	}

	// Отчества вырезаны.
	for _, leak := range []string{"Ивановичем", "Петровны", "Кузьмич"} {
		if strings.Contains(res.Text, leak) {
			t.Errorf("отчество %q просочилось; got: %q", leak, res.Text)
		}
	}
	// Слова-ловушки целы (precision).
	for _, keep := range []string{"Наличие", "количество", "Различие", "отличий"} {
		if !strings.Contains(res.Text, keep) {
			t.Errorf("слово-ловушка %q ошибочно удалено; got: %q", keep, res.Text)
		}
	}
}
