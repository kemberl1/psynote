"""Однозначные опечатки модели в клинических формулировках."""

_OBVIOUS_TYPOS: tuple[tuple[str, str], ...] = (
    ("Сидрос", "Синдром"),
    ("сидрос", "синдром"),
    ("СИДРОС", "СИНДРОМ"),
    ("психмоторн", "психомоторн"),
    ("Психмоторн", "Психомоторн"),
    ("ПСИХМОТОРН", "ПСИХОМОТОРН"),
    ("самостоятельно не предъявляет", "не предъявляет"),
    ("Самостоятельно не предъявляет", "не предъявляет"),
    ("самостоятельно не формирует", "не предъявляет"),
    ("Самостоятельно не формирует", "не предъявляет"),
    ("mildly", "слегка"),
    ("Mildly", "Слегка"),
    ("slightly", "слегка"),
    ("Slightly", "Слегка"),
    ("на оклики", "на замечания"),
    ("На оклики", "На замечания"),
)


def fix_obvious_typos(text: str) -> str:
    """Заменяет только явно видимые опечатки вроде «Сидрос» → «Синдром»."""
    if not text:
        return text
    out = text
    for src, dst in _OBVIOUS_TYPOS:
        if src in out:
            out = out.replace(src, dst)
    return out
