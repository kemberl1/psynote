"""Структура шаблонов дневников — жёсткий каркас промпта (docs/03 §7).

Актуальная форма — бланк МИС отделения (ежедневный осмотр и осмотр
за 10 дней), а НЕ устаревшие .odt в корпусе. Образцы RAG задают только
клинический стиль психического статуса; шапка, порядок строк, дата/время
и подпись берутся исключительно отсюда.

doc_type:
  • daily    — ежедневный «ОСМОТР ЛЕЧАЩИМ ВРАЧОМ».
  • exam_10d — «ОСМОТР / лечащим врачом совместно с заведующим отделением»
               (раз в 10 дней), с этапным эпикризом.
"""

from __future__ import annotations

from dataclasses import dataclass

DOC_TYPE_DAILY = "daily"
DOC_TYPE_EXAM_10D = "exam_10d"
SUPPORTED_DOC_TYPES = (DOC_TYPE_DAILY, DOC_TYPE_EXAM_10D)

# Нейтральные плейсхолдеры вместо реальных ПДн (docs/03 §8). Подставляются
# врачом локально на этапе экспорта (docs/07 §7) — в генерацию ПДн не уходят.
# [ДАТА] / [ВРЕМЯ] на экспорте становятся
# «13» августа 2026 г. время: 10 час. 00 мин.
PLACEHOLDER_DATE = "[ДАТА]"
PLACEHOLDER_TIME = "[ВРЕМЯ]"
PLACEHOLDER_DOCTOR = "[ФИО_ВРАЧА]"
PLACEHOLDER_POSITION = "[ДОЛЖНОСТЬ_ВРАЧА]"
PLACEHOLDER_HEAD = "[ФИО_ЗАВ_ОТДЕЛЕНИЕМ]"
PLACEHOLDER_CASE_NO = "[НОМЕР_ИБ]"


@dataclass(frozen=True)
class DiaryTemplate:
    """Описание структуры шаблона дневника для каркаса промпта."""

    doc_type: str
    title: str
    header_lines: tuple[str, ...]
    # (название раздела, значение по умолчанию). Пустая строка — раздел
    # обязателен, модель должна написать содержание.
    sections: tuple[tuple[str, str], ...]
    footer_lines: tuple[str, ...]
    # После этих разделов в бланке — пустая строка.
    blank_after: tuple[str, ...] = ()

    def render_skeleton(self) -> str:
        """Текстовый каркас шаблона: каждая строка как в бланке МИС."""
        parts: list[str] = []
        parts.extend(self.header_lines)
        parts.append("")
        for name, default in self.sections:
            parts.append(f"{name}: {default}".rstrip())
            if name in self.blank_after:
                parts.append("")
        parts.append("")
        parts.extend(self.footer_lines)
        return "\n".join(parts)


