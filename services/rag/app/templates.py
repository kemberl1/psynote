"""Структура шаблонов дневников — жёсткий каркас промпта (docs/03 §7).

Шаблоны (`шаблон каждый день.odt`, `шаблон раз в 10 дней.odt`) задают
ОБЯЗАТЕЛЬНУЮ структуру и порядок разделов итогового документа. Они
используются как каркас промпта, а НЕ как материал для свободной генерации
(docs/03 §7): шаблон → структура, RAG-образцы → стиль, опросник → содержание.

Здесь структура шаблонов зафиксирована как порядок именованных разделов
(распарсено из реальных .odt корпуса). Реальные ПДн (ФИО врача, № ИБ, дата,
ЭЦП) в каркас НЕ попадают — вместо них плейсхолдеры (docs/03 §8): дату/ФИО
врач подставляет уже вне системы при экспорте (docs/05 §2.3, docs/07 §7).

doc_type:
  • daily    — ежедневный «ОСМОТР ЛЕЧАЩИМ ВРАЧОМ».
  • exam_10d — расширенный «ОСМОТР лечащим врачом совместно с зав. отделением»
               (раз в 10 дней), с этапным эпикризом.
"""

from __future__ import annotations

from dataclasses import dataclass

DOC_TYPE_DAILY = "daily"
DOC_TYPE_EXAM_10D = "exam_10d"
SUPPORTED_DOC_TYPES = (DOC_TYPE_DAILY, DOC_TYPE_EXAM_10D)

# Нейтральные плейсхолдеры вместо реальных ПДн (docs/03 §8). Подставляются
# врачом локально на этапе экспорта (docs/07 §7) — в генерацию ПДн не уходят.
PLACEHOLDER_DATE = "[ДАТА]"
PLACEHOLDER_TIME = "[ВРЕМЯ]"
PLACEHOLDER_DOCTOR = "[ФИО_ВРАЧА]"
PLACEHOLDER_HEAD = "[ФИО_ЗАВ_ОТДЕЛЕНИЕМ]"
PLACEHOLDER_CASE_NO = "[НОМЕР_ИБ]"


@dataclass(frozen=True)
class DiaryTemplate:
    """Описание структуры шаблона дневника для каркаса промпта."""

    doc_type: str
    title: str
    # Заголовок документа (шапка) с плейсхолдерами вместо ПДн.
    header_lines: tuple[str, ...]
    # Упорядоченные разделы тела: (название раздела как в шаблоне).
    sections: tuple[str, ...]
    # Подпись (плейсхолдеры) — добавляется в конце.
    footer_lines: tuple[str, ...]

    def render_skeleton(self) -> str:
        """Текстовый каркас шаблона для вставки в промпт (раздел + двоеточие)."""
        parts: list[str] = []
        parts.extend(self.header_lines)
        for sec in self.sections:
            parts.append(f"{sec}:")
        parts.extend(self.footer_lines)
        return "\n".join(parts)


