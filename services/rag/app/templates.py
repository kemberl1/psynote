_TEMPLATES: dict[str, DiaryTemplate] = {
    DOC_TYPE_DAILY: DAILY_TEMPLATE,
    DOC_TYPE_EXAM_10D: EXAM_10D_TEMPLATE,
}


def get_template(doc_type: str) -> DiaryTemplate:
    """Вернуть структуру шаблона по типу. Бросает ValueError при неизвестном типе."""
    try:
        return _TEMPLATES[doc_type]
    except KeyError as exc:
        raise ValueError(
            f"Неизвестный тип документа '{doc_type}'. "
            f"Поддерживаются: {', '.join(SUPPORTED_DOC_TYPES)}") from exc
