def _format_samples(samples: list[dict]) -> str:
    """Few-shot блок из обезличенных образцов корпуса (docs/03 §8 [CONTEXT])."""
    if not samples:
        return ("(образцы из корпуса отсутствуют — опирайся только на шаблон и "
                "ответы опросника)")
    lines: list[str] = []
    for i, s in enumerate(samples, 1):
        text = (s.get("text") or "").strip()
        if not text:
            continue
        meta_bits = []
        for key in ("syndrome", "diagnosis_class", "dynamics"):
            if s.get(key):
                meta_bits.append(f"{key}={s[key]}")
        meta = f" ({', '.join(meta_bits)})" if meta_bits else ""
        lines.append(f"--- Образец {i}{meta} ---\n{text}")
    return "\n\n".join(lines) if lines else "(образцы пусты)"


def build_messages(doc_type: str, mapped: MappedAnswers,
                   samples: list[dict]) -> list[LLMMessage]:
    """Собрать список сообщений чата для LLM (docs/03 §8).

    Разделение ролей:
      • system — инструкция + жёсткий каркас шаблона;
      • user   — few-shot образцы + ответы опросника + финальная инструкция.
    """
    template: DiaryTemplate = get_template(doc_type)

    system_content = (
        _system_prompt(doc_type)
        + "\n\n[СТРУКТУРА ШАБЛОНА — единственный каркас; копируй названия "
        "и порядок строк буквально. Значения после двоеточия в каркасе — "
        "дефолты бланка: подставляй их, если в ответах нет иного. "
        "Образцы корпуса для структуры ИГНОРИРУЙ.]\n"
        + template.render_skeleton()
    )

    # Нарративный контекст пакетной генерации (из __arc_context__ в answers).
    # Инжектируется в системный промпт — содержит клинические детали и позицию
    # дня в дуге, которые ДОЛЖНЫ активно использоваться в тексте дневника.
    if mapped.director_note:
        system_content += (
            "\n\n[БРИФ ЭТОГО ДНЯ — сценарий, не текст для копирования]\n"
            "Ниже — раскладка ИМЕННО сегодняшнего дня госпитализации. "
            "Переведи пункты в язык наблюдающего врача. Не цитируй бриф "
            "дословно, не перепечатывай эпикриз периода, не тащи чужие дни.\n"
            + mapped.director_note
        )

    answers_block = "\n".join(f"- {line}" for line in mapped.prompt_lines) \
        or "- (ответы не предоставлены)"

    user_content = (
        "[ОБРАЗЦЫ ИЗ КОРПУСА — так пишут опытные психиатры; задают стиль и "
        "конкретность описания]\n"
        + _format_samples(samples)
        + "\n\n[ОТВЕТЫ ОПРОСНИКА — клиническая информация по пациенту]\n"
        + answers_block
        + "\n\n[ЗАДАНИЕ]\nНапиши "
        + ("ежедневный дневник" if doc_type == DOC_TYPE_DAILY
           else "расширенный осмотр (раз в 10 дней) с этапным эпикризом")
        + " строго по каркасу шаблона (образцы корпуса — только стиль статуса, "
        "не порядок строк и не шапка). "
        "Используй конкретные детали поведения, речи и аффекта пациента — "
        "избегай пустых фраз типа «состояние удовлетворительное» или «поведение "
        "упорядоченное» без раскрытия через наблюдения. "
        "КРИТИЧЕСКИ ВАЖНО: если нарративный контекст содержит конкретные события "
        "(визит родственника, инцидент, самоповреждение, острый эпизод) — "
        "они уже отфильтрованы специально для этого дня. Отражай их в дневнике "
        "с полным клиническим весом. Если контекст содержит только общее состояние "
        "без конкретных событий — пиши 'тихий день' с конкретными наблюдениями "
        "без придумывания событий, которых нет в портрете. "
        "Быт отделения (палата, игровая, обособленность) можно конкретизировать "
        "из эпикриза; прогулки, визиты и выходные не в тот день — нельзя. "
        "Варьируй формулировки: не используй одинаковые фразы для сна, аппетита, "
        "контакта, поведения — каждый день должен звучать чуть по-другому. "
        "Реальные ФИО и даты не подставляй — "
        f"используй плейсхолдеры {PLACEHOLDER_DATE} и {PLACEHOLDER_DOCTOR}."
    )

    return [
        LLMMessage(role="system", content=system_content),
        LLMMessage(role="user", content=user_content),
    ]


def build_query_text(mapped: MappedAnswers, doc_type: str) -> str:
    """Поисковый текст для retrieval (docs/03 §6 п.1) из формулировок ответов.

    Если ответов мало, добавляем тип документа как опорный контекст.
    """
    base = mapped.query_text.strip()
    type_hint = ("ежедневный дневник психиатрический"
                 if doc_type == DOC_TYPE_DAILY
                 else "расширенный психиатрический осмотр этапный эпикриз")
    if mapped.syndrome:
        base = f"{mapped.syndrome} {base}"
    return f"{type_hint} {base}".strip()
