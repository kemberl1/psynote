_STATUS_START_RE = re.compile(r"(?:\*\*)?Психический статус[^:\n]*:", re.I)
_STATUS_END_RE = re.compile(
    r"\n\s*(?:\*\*)?(?:Соматический статус|Неврологический статус|Диагноз|"
    r"Основное заболевание|Назначения|План |Этапный эпикриз|Выполнены)",
    re.I,
)
_SAMPLE_LIMIT = 900


def style_excerpt(text: str, limit: int = _SAMPLE_LIMIT) -> str:
    """Из образца — абзац психического статуса, а не первые N символов.

    У «full»-чанков начало — шапка старого бланка (жалобы, анамнез), и при
    обрезке по длине модель почти не видела сам статус — ради него и RAG.
    """
    m = _STATUS_START_RE.search(text)
    if m:
        body = text[m.start():]
        end = _STATUS_END_RE.search(body)
        text = (body[:end.start()] if end else body).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    sentence_end = cut.rfind(". ")
    if sentence_end > limit // 2:
        return cut[:sentence_end + 1]
    return cut.rsplit(" ", 1)[0] + "…"


def _format_samples(samples: list[dict]) -> str:
    """Few-shot блок из обезличенных образцов корпуса (docs/03 §8 [CONTEXT])."""
    if not samples:
        return ("(образцы из корпуса отсутствуют — опирайся только на шаблон и "
                "ответы опросника)")
    lines: list[str] = []
    for i, s in enumerate(samples, 1):
        text = style_excerpt(sanitize_corpus_sample((s.get("text") or "").strip()))
        if not text:
            continue
        meta_bits = []
        for key in ("syndrome", "diagnosis_class", "dynamics"):
            if s.get(key):
                meta_bits.append(f"{key}={s[key]}")
        meta = f" ({', '.join(meta_bits)})" if meta_bits else ""
        lines.append(f"--- Образец {i}{meta} ---\n{text}")
    return "\n\n".join(lines) if lines else "(образцы пусты)"


def build_messages(doc_type: str, mapped: MappedAnswers,
                   samples: list[dict]) -> list[LLMMessage]:
    """Собрать список сообщений чата для LLM (docs/03 §8).

    Разделение ролей:
      • system — инструкция + жёсткий каркас шаблона;
      • user   — few-shot образцы + ответы опросника + финальная инструкция.
    """
    template: DiaryTemplate = get_template(doc_type)

    system_content = (
        _system_prompt(doc_type)
        + "\n\n[СТРУКТУРА ШАБЛОНА — единственный каркас; копируй названия "
        "и порядок строк буквально. Значения после двоеточия в каркасе — "
        "дефолты бланка: подставляй их, если в ответах нет иного. "
        "Образцы корпуса для структуры ИГНОРИРУЙ.]\n"
        + template.render_skeleton()
    )

    # Нарративный контекст пакетной генерации (из __arc_context__ в answers).
    # Инжектируется в системный промпт — содержит клинические детали и позицию
    # дня в дуге, которые ДОЛЖНЫ активно использоваться в тексте дневника.
    if mapped.director_note:
        system_content += (
            "\n\n[БРИФ ЭТОГО ДНЯ — сценарий, не текст для копирования]\n"
            "Ниже — раскладка ИМЕННО сегодняшнего дня госпитализации. "
            "Переведи пункты в язык наблюдающего врача. Не цитируй бриф "
            "дословно, не перепечатывай эпикриз периода, не тащи чужие дни.\n"
            + mapped.director_note
        )

    answers_block = "\n".join(f"- {line}" for line in mapped.prompt_lines) \
        or "- (ответы не предоставлены)"

    user_content = (
        "[ОБРАЗЦЫ ИЗ КОРПУСА — только СТИЛЬ психического статуса: как формулируют "
        "контакт, аффект, поведение. Это ДРУГИЕ пациенты. Запрещено брать из образцов "
        "диагноз, интеллект, уровень речи, препараты, визиты, интернат, "
        "направление на госпитализацию и эпизоды, которых нет "
        "в ответах и брифе сегодня. «Мягкая фиксация» в образце — это СТИЛЬ "
        "каскада при возбуждении, не факт про ЭТОГО ребёнка; "
        "«физическое удержание» не копируй никогда.]\n"
        + _format_samples(samples)
        + "\n\n[ОТВЕТЫ ОПРОСНИКА — клиническая информация по пациенту]\n"
        + answers_block
        + "\n\n[ЗАДАНИЕ]\nНапиши "
        + ("ежедневный дневник" if doc_type == DOC_TYPE_DAILY
           else "расширенный осмотр (раз в 10 дней) с этапным эпикризом")
        + " строго по каркасу шаблона. Образцы корпуса — только стиль "
        "психического статуса: ни порядка строк, ни шапки, ни чужой диагноз, "
        "интеллект, речь и препараты из них не бери.\n"
        "Пиши конкретные наблюдения за поведением, речью и аффектом, а не "
        "«состояние удовлетворительное» без раскрытия. События из брифа уже "
        "отфильтрованы под этот день — отрази их с полным клиническим весом; "
        "если событий нет, это тихий день, и выдумывать их нельзя.\n"
        "Терапия и инъекции — только в «План лечения» и только из брифа; "
        "«Назначения» — «см. лист назначений»; меры стеснения — только если "
        "врач указал их сегодня.\n"
        "Этапный эпикриз осмотра 10 дней — период ДО сегодняшней даты, без "
        "выписки и без схемы, начавшейся позже.\n"
        "Не оставляй [УЧРЕЖДЕНИЕ] и [НОМЕР_ДОКУМЕНТА]; реальные ФИО и даты не "
        f"подставляй — плейсхолдеры {PLACEHOLDER_DATE} и {PLACEHOLDER_DOCTOR}."
    )

    return [
        LLMMessage(role="system", content=system_content),
        LLMMessage(role="user", content=user_content),
    ]


def build_query_text(mapped: MappedAnswers, doc_type: str) -> str:
    """Поисковый текст: стиль статуса + наблюдения СЕГОДНЯ, не штамп опросника.

    Если врач сегодня указал фиксацию — ищем формулу корпуса «мягкая фиксация».
    """
    type_hint = ("ежедневный дневник психический статус"
                 if doc_type == DOC_TYPE_DAILY
                 else "расширенный психиатрический осмотр психический статус")
    parts: list[str] = [type_hint]
    if mapped.syndrome:
        parts.append(mapped.syndrome)
    obs = observation_query_fragment(mapped.director_note)
    if obs:
        parts.append(obs)
    elif mapped.query_text.strip():
        parts.append(mapped.query_text.strip())
    if query_mentions_fixation(mapped):
        parts.append(FIXATION_STYLE_QUERY)
    return " ".join(parts).strip()


FIXATION_STYLE_QUERY = (
    "мягкая фиксация конечностей на 20 минут под контролем медперсонала "
    "вербальной коррекции не поддавался на замечания реагировал остро "
    "после фиксации успокоился"
)

def observation_query_fragment(director_note: str | None) -> str:
    """Только пункты «СЕГОДНЯ» из брифа — без запретов и каркаса."""
    if not director_note:
        return ""
    lines: list[str] = []
    capture = False
    for raw in director_note.splitlines():
        line = raw.strip()
        if "СЕГОДНЯ опиши" in line:
            capture = True
            continue
        if not capture:
            continue
        if line.startswith(("•", "-", "–")):
            lines.append(line.lstrip("•-– ").strip())
            continue
        if lines and (
            line.startswith("Сегодня коррекция")
            or line.startswith("Терапию")
            or line.startswith("ЗАПРЕЩЕНО")
            or line.startswith("ГРАМОТНО")
            or line.startswith("Интернат")
            or line.startswith("Фон/")
        ):
            break
    return " ".join(lines).strip()


def query_mentions_fixation(mapped: MappedAnswers) -> bool:
    """Мягкая фиксация — только если врач указал её в наблюдениях СЕГОДНЯ.

    Возбуждение само по себе не повод: мера стеснения в медицинском
    документе пишется только со слов врача.
    """
    return "фиксац" in observation_query_fragment(mapped.director_note).lower()
